# -*- coding: utf-8 -*-
r"""Объём чтения и стоимость под уточнённый состав данных (19.11.2026).

Состав:
  отчёт ТЕКУЩЕГО года  — баланс, ОФР, ОДДС (из ОДДС нужен только код 4100);
  отчёт ПРОШЛОГО года  — баланс и ОДДС (4100); ОФР за прошлый год не нужен.

Главное, что здесь показано: **объём чтения — это страницы форм, а не страницы документа.**
Прежняя проекция «4 159 страниц × 0.055 ₽» считала чтением каждую страницу, включая
пояснения, которые модель не открывает вовсе.

Все ставки — из фактических счетов, не из прайса:
  полное структурирование ОДДС   0.65 ₽  (Кокс_9мес_2025, 1 905 вх / 34 078 вых)
  извлечение одного кода 4100    0.05 ₽  (измерено 0.010-0.104 ₽ на четырёх документах)
  прочитанная страница           0.09 ₽  (gemini, ~1 200 вх / 2 000-6 000 вых)
  страница детекции              0.0023 ₽

Запуск: python _объём_и_смета.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

CF_FULL = 0.65     # полное структурирование ОДДС (измерено)
CF_LIGHT = 0.05    # извлечение только 4100 (измерено)
RATE_PAGE = 0.09   # прочитанная страница
RATE_DETECT = 0.0023

# Факт по разобранным отчётам: страницы по формам и фактическая стоимость прогона
# 02.11.2026 (до смены состава данных). cost=None — документ не мерился отдельно.
OBSERVED = {
    'Кокс_9мес_2025':            dict(pages=7,  balance=[1, 2],       cf=[],         isf=[],        cost=0.603),
    'Рубеж_9мес_2025':           dict(pages=19, balance=[1, 2, 3],    cf=[],         isf=[],        cost=0.540),
    'Энерготехсервис_9мес_2025': dict(pages=12, balance=[1, 2, 3, 4], cf=[],         isf=[],        cost=0.745),
    'Рубеж_9мес_2026':           dict(pages=18, balance=[1, 2],       cf=[8, 9, 10], isf=[3, 4],    cost=1.323),
    'Автобан_9мес_2026':         dict(pages=10, balance=[],           cf=[8, 9, 10], isf=[3, 4],    cost=0.447),
}

DOCS_TOTAL = 270          # 135 эмитентов × 2 года
CORPUS_AVG_PAGES = 34.0   # средняя длина документа по всей папке (57 док., 1 946 стр.)


def new_cost(name, d):
    """Стоимость документа при новом составе данных, от фактической старой.

    Меняется ровно одно место: ОДДС. Раньше он структурировался целиком (0.65 ₽),
    теперь из него извлекается один код (0.05 ₽). Для документов, где ОДДС не читался
    вовсе (прошлый год), он появляется — и стоит те же 0.05 ₽ плюс страница чтения.
    """
    old = d['cost']
    if d['cf']:
        # не ниже нуля: у «Автобан_9мес_2026» баланс не прочитан, и вычитание полной
        # стоимости ОДДС из его счёта даёт отрицательную величину — это артефакт
        # вычитания, а не экономия
        return max(old - CF_FULL + CF_LIGHT, CF_LIGHT)
    return old + CF_LIGHT + RATE_PAGE


def main():
    print('=== 1. ФАКТ: страницы форм в разобранных отчётах ===')
    print(f'{"документ":<30}{"всего":>7}{"баланс":>8}{"ОФР":>6}{"ОДДС":>6}{"нужно 4100":>12}')
    for name, d in OBSERVED.items():
        need = 1 if d['cf'] else 0
        print(f'{name:<30}{d["pages"]:>7}{len(d["balance"]):>8}{len(d["isf"]):>6}'
              f'{len(d["cf"]):>6}{need:>12}')

    print()
    print('=== 2. ЧТО ЧИТАЕТ МОДЕЛЬ, А ЧТО ТОЛЬКО ДЕТЕКЦИЯ ===')
    for name, d in OBSERVED.items():
        forms = len(d['balance']) + len(d['isf']) + (1 if d['cf'] else 0)
        read = forms + 1   # + титульная страница
        print(f'  {name:<30} документ {d["pages"]:>2} стр.  ->  читается {read:>2} стр. '
              f'({read / d["pages"] * 100:.0f}%), детекция смотрит все {d["pages"]}')
    avg_read = sum(len(d['balance']) + len(d['isf']) + (1 if d['cf'] else 0) + 1
                   for d in OBSERVED.values()) / len(OBSERVED)
    print(f'  в среднем читается {avg_read:.1f} стр. из 12 в этих документах')

    print()
    print('=== 3. СМЕТА НА 135 ЭМИТЕНТОВ ===')
    new = {k: new_cost(k, d) for k, d in OBSERVED.items()}
    print(f'{"документ":<30}{"было ₽":>9}{"стало ₽":>9}{"дельта":>9}')
    for k in OBSERVED:
        print(f'{k:<30}{OBSERVED[k]["cost"]:>9.2f}{new[k]:>9.2f}{new[k] - OBSERVED[k]["cost"]:>+9.2f}')
    per_doc = sum(new.values()) / len(new)
    print()
    print(f'  среднее на документ: {per_doc:.2f} ₽  (было {sum(d["cost"] for d in OBSERVED.values()) / len(OBSERVED):.2f} ₽)')
    print(f'  {DOCS_TOTAL} документов -> {per_doc * DOCS_TOTAL:.0f} ₽')

    print()
    print('=== 4. ОТКУДА ЭКОНОМИЯ ===')
    with_cf = sum(1 for d in OBSERVED.values() if d['cf'])
    print(f'  «нужен только 4100»: ОДДС {CF_FULL:.2f} ₽ -> {CF_LIGHT:.2f} ₽ на каждом документе с ОДДС')
    print(f'    на замере это {with_cf} документа из {len(OBSERVED)}; '
          f'на 270 документах — ориентировочно {(CF_FULL - CF_LIGHT) * DOCS_TOTAL * 0.8:.0f} ₽')
    print(f'  прошлый год: ОФР не читается вовсе')
    print(f'  ОДДС читается до страницы с 4100: на «Рубеж» и «Автобан» это 1 стр. вместо 3')

    print()
    print('=== 5. ВРЕМЯ (узкое место — детекция всех страниц, 4 потока) ===')
    detect_pages = DOCS_TOTAL * CORPUS_AVG_PAGES
    print(f'  страниц под детекцию: {detect_pages:.0f}  (270 док. × {CORPUS_AVG_PAGES:.0f} стр.)')
    for sec in (8, 12, 20):
        print(f'    при {sec:>2} с на вызов: {detect_pages * sec / 4 / 3600:.1f} ч')
    print(f'  страниц на чтение моделью: {avg_read * DOCS_TOTAL:.0f}')


if __name__ == '__main__':
    main()