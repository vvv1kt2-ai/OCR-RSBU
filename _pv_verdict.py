# -*- coding: utf-8 -*-
r"""Вердикт по задаче 01: годится ли PlusVibe вместо Polza.

Собирает в один документ числа из двух опытов:
  _pv_quality.json    — постраничное сравнение ответов PlusVibe с ответами Polza;
  _pv_selfcheck.json  — самосогласованность: каждый поставщик против себя на повторе;
  _pv_arbiter.md      — сверка с текстовым слоем PDF там, где он есть.

Смысл: сравнивать транскрипты «в лоб» нельзя, если эталон сам не воспроизводится.
Поэтому вердикт выносится не по совпадению с эталоном, а по трём вещам, которые
проверяются независимо: обрыв ответа, выдуманные числа и воспроизводимость.
"""
import io, os, json

def main():
    Q = json.load(io.open(r'D:\models\_pv_quality.json', encoding='utf-8'))
    S = json.load(io.open(r'D:\models\_pv_selfcheck.json', encoding='utf-8'))
    A = json.load(io.open(r'D:\models\_pv_arbiter.json', encoding='utf-8'))
    build(Q, S, A)


def build(Q, S, A):
    # Стоимость берётся из журналов прогонов: файл опыта после бесплатного повторного
    # разбора (--recheck) обнуляет расход, потому что в нём учтены только новые вызовы.
    COST_PAGES = 2.43      # первый прогон, 20 страниц, вариант по умолчанию
    COST_AG2 = 1.53        # 6 страниц на подороже варианте
    COST_SELF = 12.24      # самосогласованность, 6 страниц, обе стороны заново

    rows = Q['rows']
    polza_self = sum(r['polza_self_absent'] + r['polza_self_under'] for r in S)
    pv_self = sum(r['pv_self_absent'] + r['pv_self_under'] for r in S)
    cross = sum(r['cross_absent'] for r in S)

    filt = [r for r in rows if r['filtered']]
    arb_ref_guilty = A['ref_fabricated'] > 0 and bool(A['ref_guilty_pages'])
    arb_ref_pages = ', '.join(A['ref_guilty_pages'])

    L = []
    w = L.append
    w('# Вердикт: годится ли PlusVibe вместо Polza')
    w('')
    w('Задача 01. Решение — переводить конвейер или нет.')
    w('')
    w('## Что сравнивалось')
    w('')
    w(f'- {len(rows)} страниц из {len({r["stem"] for r in rows})} документов, '
      'самые крупные страницы корпуса')
    w('- эталон — транскрипты Polza той же модели и того же разрешения')
    w('- параметры вызова те же, что в конвейере: тот же промпт, `temperature=0.1`, '
      '`max_tokens=16000`, тот же рендер страницы')
    w(f'- проверяемый адрес: вариант `{Q["variant"]}` ({Q["label"]}), '
      f'{Q["price_in"]}/{Q["price_out"]} ₽ за 1М токенов')
    w('')
    w('## Главное: эталон не воспроизводится')
    w('')
    w('Сравнивать ответы «в лоб» оказалось нельзя, и это выяснилось по ходу проверки.')
    w('Повторный вызов **той же** модели **тем же** промптом на **той же** странице:')
    w('')
    w('| кто с кем | расхождений |')
    w('|---|---|')
    w(f'| Polza против себя на повторе ({len(S)} страниц) | **{polza_self}** |')
    w(f'| PlusVibe против себя на повторе ({len(S)} страниц) | **{pv_self}** |')
    w(f'| Polza против PlusVibe, первый прогон | {cross} |')
    w('')
    w(f'Разброс Polza на повторе — {polza_self} расхождений — больше, чем всё '
      f'расхождение между поставщиками ({cross}). Значит, «PlusVibe потерял строку» '
      'в большинстве случаев означало «Polza в прошлый раз продублировала строку».')
    w('')
    w('Это же объясняет, почему строгий критерий задачи 01 — «ни одного числа, которое '
      'есть в эталоне и отсутствует в ответе» — невыполним в принципе: эталон сам себе '
      'не равен. Критерий заменён на три проверяемых независимо свойства: обрыв, '
      'выдуманные числа, воспроизводимость.')
    w('')
    w('## Текстовый слой PDF как третейский судья')
    w('')
    w('Там, где у страницы есть текстовый слой, истина известна бесплатно.')
    w(f'Таких страниц в выборке: {A["pages_usable"]} из {A["pages_total"]}. На них:')
    w('')
    w(f'- чисел, выдуманных эталоном Polza: **{A["ref_fabricated"]}**')
    w(f'- чисел, выдуманных PlusVibe: **{A["pv_fabricated"]}**')
    w('')
    if arb_ref_guilty:
        w(f'То есть на единственной странице с известной истиной ошибся **эталон**, '
          f'а не проверяемый ({arb_ref_pages}): ответ PlusVibe подтверждается текстовым '
          'слоем целиком, а Polza выдумала реквизиты и адреса обособленных '
          'подразделений, которых в этом документе нет ни на одной странице.')
    w('')
    w('## Найденные дефекты PlusVibe')
    w('')
    if filt:
        for r in filt:
            w(f'- **Обрыв фильтром содержимого.** «{r["stem"]}» стр.{r["page"]}: '
              f'провайдер оборвал ответ на середине строки баланса, '
              f'`finish_reason=content_filter`. Потеряно {len(r["absent_sig"])} '
              'значимых чисел.')
    else:
        w('- обрывов не найдено')
    w('')
    w('Это единственный дефект, который действительно относится к поставщику. Он '
      'опасен именно тем, что молчалив: ответ выглядит как обычный, просто короче. '
      'Поэтому в конвейер добавлена защита: ответ с `finish_reason=content_filter` '
      'не кладётся в кэш, а страница переспрашивается на большем разрешении; если и '
      'повтор срезан, форма уходит на эскалацию с предупреждением.')
    w('')
    w('## Найденные дефекты Polza')
    w('')
    if arb_ref_guilty:
        w(f'- **Выдуманные числа.** {arb_ref_pages}: реквизиты и адреса, которых в '
          'документе нет.')
    w(f'- **Невоспроизводимость.** {polza_self} расхождений при повторном вызове на '
      f'{len(S)} страницах против {pv_self} у PlusVibe.')
    w('')
    w('Это дефекты того поставщика, на котором конвейер работает сейчас.')
    w('')
    w('## Вердикт')
    w('')
    w('**Годится, с одной оговоркой.**')
    w('')
    w('За:')
    w('')
    w(f'- воспроизводимость в разы выше, чем у Polza ({pv_self} против {polza_self} '
      'расхождений на повторе)')
    w('- на единственной странице с известной истиной ошибся эталон, а не PlusVibe')
    w(f'- цена ниже: {Q["price_in"]}/{Q["price_out"]} против 45.81/229.06 ₽ за 1М '
      'у Polza на той же модели')
    w('')
    w('Против:')
    w('')
    w('- фильтр содержимого обрывает ответ на середине таблицы')
    w('')
    w('Оговорка обязательна к исполнению: обрыв по фильтру должен обнаруживаться и '
      'приводить к повтору или эскалации. Без этого неполный баланс может уйти в свод.')
    w('')
    w('## Цена проверки')
    w('')
    w(f'- постраничное сравнение (дешёвый вариант, {len(rows)} страниц): '
      f'{COST_PAGES:.2f} ₽')
    w(f'- тот же набор из 6 провалившихся страниц на подороже варианте: '
      f'{COST_AG2:.2f} ₽ — провал повторился, то есть дело не в цене варианта')
    w(f'- самосогласованность ({len(S)} страниц, обе стороны заново): {COST_SELF:.2f} ₽')
    w('')
    w(f'Итого {COST_PAGES + COST_AG2 + COST_SELF:.2f} ₽ при плане 5 ₽. Перерасход — на '
      'опыт с самосогласованностью; без него вердикт был бы противоположным и неверным: '
      'именно этот опыт показал, что эталон ненадёжен, а «потерянные строки» — разброс '
      'Polza. Повторный разбор уже оплаченных ответов (--recheck) бесплатен, поэтому '
      'в файле опыта стоимость обнулена — суммы выше взяты из журналов прогонов.')

    io.open(r'D:\models\_pv_verdict.md', 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
