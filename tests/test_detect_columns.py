# -*- coding: utf-8 -*-
r"""Тест разбора заголовков колонок, когда год стоит ОТДЕЛЬНОЙ строкой.

Дефект: `detect_columns` требовал год сразу после месяца (`На 30 июня 2026 г.`). В реальном
слое шапка разбита как «На 30 июня / На 31 декабря / 2026 г.», год второй колонки отсутствует
вовсе. Дат находилось ноль, функция возвращала пустой список, `columns=[]`, и баланс в своде
оставался пустым — 18 клеток (замер: `АСГ Трансформаторен_6мес_2026`).

Отдельная ловушка: при таком порядке строк старый регекс давал ЛОЖНУЮ дату 31.12.2026 —
год «прилипал» к «На 31 декабря» через перевод строки. Тест следит и за этим: выдуманной
декабрьской даты в результате быть не должно.

Вывод года — ДОГАДКА по раскладке баланса за 6 месяцев, поэтому он обязан попадать в warnings.

Без вызовов модели. Запуск: python D:\models\tests\test_detect_columns.py
Лог:    tests\_last_run_detect_columns.txt
"""
import io
import os
import sys

sys.path.insert(0, r'D:\models\pylibs')
sys.path.insert(0, r'D:\models')
import pipeline as P

LOG = io.open(os.path.join(r'D:\models\tests', '_last_run_detect_columns.txt'), 'w',
              encoding='utf-8')
ok = fail = 0


def check(name, cond, detail=''):
    global ok, fail
    if cond:
        ok += 1
        LOG.write(f'  OK   {name}\n')
    else:
        fail += 1
        LOG.write(f'  ПРОВАЛ {name} {detail}\n')


def cols(text):
    w = []
    return P.detect_columns(text, warnings=w), w


# ─── 1. обычные заголовки: поведение не изменилось ───
c, w = cols('На 30 июня 2026 г.   На 31 декабря 2025 г.')
check('обычная шапка баланса -> две даты', c == ['2026-06-30', '2025-12-31'], str(c))
check('на обычной шапке предупреждений нет', w == [], str(w))

c, w = cols('На 30 июня 2026 г.  На 31 декабря 2025 г.  На 31 декабря 2024 г.')
check('три колонки баланса -> три даты',
      c == ['2026-06-30', '2025-12-31', '2024-12-31'], str(c))

c, w = cols('За 1 полугодие 2026 г.   За 1 полугодие 2025 г.')
check('ОФР: периоды не тронуты', c == ['За 1 полугодие 2026 г.', 'За 1 полугодие 2025 г.'], str(c))
check('на ОФР предупреждений нет', w == [], str(w))

# ─── 2. измеренный случай: год отдельной строкой ───
ASG = 'Пояснения \nНаименование локазателя \nКод \nНа 30 июня \nНа 31 декабря\n2026 г. \nПАССИВ \n'
c, w = cols(ASG)
check('год отдельной строкой -> колонки восстановлены',
      c == ['2026-06-30', '2025-12-31'], str(c))
check('ложная дата 31.12.2026 не появилась', '2026-12-31' not in c, str(c))
check('вывод года объявлен предупреждением',
      len(w) == 1 and 'ДОГАДКА' in w[0], str(w))
check('предупреждение называет обе колонки',
      bool(w) and '2026-06-30' in w[0] and '2025-12-31' in w[0], str(w))

# ─── 3. ничего не выдумывать, когда оснований нет ───
c, w = cols('На 30 июня \nНа 31 декабря\n')
check('нет года вообще -> пусто, а не догадка', c == [], str(c))
check('без года предупреждения нет', w == [], str(w))

c, w = cols('На 30 июня \n2026 г. \n')
check('одна дата без года -> пусто (нужны минимум две)', c == [], str(c))

c, w = cols('На 31 декабря \n2026 г. \n')
check('первая дата не июньская -> догадки нет', c == [], str(c))
check('неиюньская раскладка не даёт предупреждения', w == [], str(w))

c, w = cols('')
check('пустой текст -> пусто', c == [], str(c))

# ─── 4. warnings необязателен (старые вызовы не падают) ───
try:
    r = P.detect_columns(ASG)
    check('вызов без warnings не падает и даёт те же колонки',
          r == ['2026-06-30', '2025-12-31'], str(r))
except TypeError as e:
    check('вызов без warnings не падает и даёт те же колонки', False, str(e))

# ─── 5. проверка на реальном PDF, если он есть ───
p = r'D:\data-scraping\downloads\АСГ Трансформаторен_6мес_2026.pdf'
if os.path.exists(p):
    import pymupdf
    d = pymupdf.open(p)
    lines = []
    for pg in (3, 4):
        if pg <= len(d):
            lines.extend(d[pg - 1].get_text().splitlines())
    c, w = cols('\n'.join(lines[:120]))
    check('реальный АСГ: колонки восстановлены',
          c == ['2026-06-30', '2025-12-31'], str(c))
    check('реальный АСГ: предупреждение о догадке есть', len(w) == 1, str(w))
else:
    LOG.write('  (PDF АСГ не найден — проверка на реальных данных пропущена)\n')

LOG.write(f'\nИТОГ: успешно {ok}, провалов {fail}\n')
LOG.close()
print(f'успешно {ok}, провалов {fail} (лог: tests/_last_run_detect_columns.txt)')
sys.exit(1 if fail else 0)
