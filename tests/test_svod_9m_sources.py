# -*- coding: utf-8 -*-
r"""Свод за 9 месяцев: откуда берутся числа и чем пустая клетка отличается от нуля.

Тест утверждает три вещи, которые до 25.11.2026 не проверял никто:

1. Источник по годам (`_СВОД_9мес_ОТЧЁТ.md` §2): баланс 2025 берётся из отчёта 2025 года,
   а ОФР и ОДДС 2025 — из СРАВНИТЕЛЬНОЙ колонки отчёта 2026 года.
2. Колонка с пробелом внутри года («За 9 мес 20 26 г.») находится. Локальная регулярка
   `_свод_9мес.flow_idx` искала непрерывную подстроку и такую колонку теряла: замер —
   `Интернешнл Петролеум Сервис (ИПС)_9мес_2026`, ОДДС `4100 = [-7712, -44779]`,
   `4110 = [161378, 573504]`, а в своде на их месте стояли нули.
3. Непрочитанная клетка остаётся ПУСТОЙ. Раньше признаком служило «форма есть», поэтому
   отсутствующая колонка и отсутствующий код строки превращались в 0 — «не читали»
   становилось неотличимо от «ноль» (`_СВОД_9мес_ОТЧЁТ.md` §7.3).

Без вызовов модели и без записи в рабочие артефакты: строятся синтетические формы.
Запуск: python D:\models\tests\test_svod_9m_sources.py
Лог:    tests\_last_run_svod_9m_sources.txt
"""
import io
import json
import os
import sys

sys.path.insert(0, r'D:\models')
import _свод_9мес as M

LOG = io.open(os.path.join(r'D:\models\tests', '_last_run_svod_9m_sources.txt'), 'w',
              encoding='utf-8')
ok = fail = 0


def check(name, cond, detail=''):
    global ok, fail
    if cond:
        ok += 1
        LOG.write(f'  OK   {name}\n')
    else:
        fail += 1
        LOG.write(f'  ПРОВАЛ {name} {detail}\n')


def form(cols, items):
    return {'columns': cols, 'items': [{'code': c, 'values': v} for c, v in items]}


def art(year, bal, isf, cf, status='ok'):
    return {'status': status, 'balance': bal, 'income_statement': isf, 'cash_flow': cf,
            'source': {'file': f'Тест_{year}.pdf'}}


# ─── 0. интерфейс: клетка обязана уметь быть пустой ───
# Без этой функции «не читали» и «ноль» неразличимы по построению, поэтому её отсутствие —
# провал, а не пропуск проверки.
check('есть функция cell_value (пустая клетка != 0)',
      hasattr(M, 'cell_value'),
      'нет _свод_9мес.cell_value — запись клетки осталась внутри main()')

# ─── 1. источник по годам (§2 отчёта) ───
B25 = form(['На 30 сентября 2025 г.', 'На 31 декабря 2024 г.'],
           [('1250', [111, 999]), ('1300', [555, 444])])
I26 = form(['За 9 мес 2026 г.', 'За 9 мес 2025 г.'], [('2110', [1000, 500])])
C26 = form(['За 9 мес 2026 г.', 'За 9 мес 2025 г.'], [('4100', [10, 20])])
B26 = form(['На 30 сентября 2026 г.', 'На 30 сентября 2025 г.'],
           [('1250', [222, 333]), ('1300', [777, 666])])

arts = {'тест': {2025: art(2025, B25, I26, C26), 2026: art(2026, B26, I26, C26)}}
row, present, _risk, has25, has26 = M.build_row(arts, 'Тест')

check('2026: баланс из отчёта 2026', row.get(('1250', 2026)) == 222,
      f'получено {row.get(("1250", 2026))!r}')
check('2025: баланс из отчёта 2025, не из сравнительной колонки 2026',
      row.get(('1250', 2025)) == 111,
      f'получено {row.get(("1250", 2025))!r} (333 — это сравнительная колонка отчёта 2026)')
check('2025: ОФР из сравнительной колонки отчёта 2026', row.get(('2110', 2025)) == 500,
      f'получено {row.get(("2110", 2025))!r}')
check('2025: ОДДС из сравнительной колонки отчёта 2026', row.get(('4100', 2025)) == 20,
      f'получено {row.get(("4100", 2025))!r}')
check('оба отчёта найдены', has25 and has26)

# ─── 2. пробел внутри года ───
SPACED = form(['За 9 мес 20 26 г.²', 'За 9 мес 20 25 г.³'], [('4100', [-7712, -44779])])
check('flow_idx: «20 26 г.» -> 0', M.flow_idx(SPACED, 2026) == 0,
      f'получено {M.flow_idx(SPACED, 2026)!r}')
check('flow_idx: «20 25 г.» -> 1', M.flow_idx(SPACED, 2025) == 1,
      f'получено {M.flow_idx(SPACED, 2025)!r}')
SPB = form(['На 30 сентября 20 26 г.', 'На 30 сентября 20 25 г.'],
           [('1250', [222, 333])])
check('bal_idx: «30 сентября 20 26 г.» -> 0', M.bal_idx(SPB, 2026) == 0,
      f'получено {M.bal_idx(SPB, 2026)!r}')

# ─── 3. колонка не найдена: пусто, не ноль ───
ONLY25 = form(['За 9 мес 2025 г.'], [('4100', [20])])
arts_b = {'тест': {2026: art(2026, B26, I26, ONLY25)}}
row_b, present_b, _r, _a, _b = M.build_row(arts_b, 'Тест')
check('нет колонки 2026: значение не подставлено', row_b.get(('4100', 2026)) is None,
      f'получено {row_b.get(("4100", 2026))!r}')
check('нет колонки 2026: клетка помечена как непрочитанная',
      not present_b.get(('4100', 2026)),
      'признак «читаемо» выставлен при отсутствующей колонке')
check('нет колонки 2026 -> пустая строка, а не 0',
      M.cell_value(None, present_b.get(('4100', 2026))) == '' if hasattr(M, 'cell_value') else False,
      f'получено {M.cell_value(None, present_b.get(("4100", 2026)))!r}'
      if hasattr(M, 'cell_value') else 'нет cell_value')

# ─── 4. код строки отсутствует в форме: пусто, не ноль ───
NO1300 = form(['На 30 сентября 2026 г.'], [('1250', [222])])
arts_c = {'тест': {2026: art(2026, NO1300, I26, C26)}}
row_c, present_c, _r, _a, _b = M.build_row(arts_c, 'Тест')
check('нет кода 1300 в форме: пусто, не 0', row_c.get(('1300', 2026)) is None,
      f'получено {row_c.get(("1300", 2026))!r}')
check('нет кода 1300: помечено как непрочитанное', not present_c.get(('1300', 2026)))

# ─── 5. прочерк при прочитанной форме — это ноль ───
DASH = form(['На 30 сентября 2026 г.'], [('1250', [None])])
arts_d = {'тест': {2026: art(2026, DASH, I26, C26)}}
row_d, present_d, _r, _a, _b = M.build_row(arts_d, 'Тест')
check('прочерк: значение None в артефакте', row_d.get(('1250', 2026)) is None)
check('прочерк: колонка и код на месте -> читаемо', bool(present_d.get(('1250', 2026))))
if hasattr(M, 'cell_value'):
    check('прочерк -> 0', M.cell_value(None, True) == 0,
          f'получено {M.cell_value(None, True)!r}')
    check('нет данных -> пусто', M.cell_value(None, False) == '',
          f'получено {M.cell_value(None, False)!r}')
    check('число не трогается', M.cell_value(-7712, True) == -7712)

# ─── 6. реальный артефакт ИПС: числа из ОДДС не должны стать нулями ───
p = os.path.join(r'D:\models\extracted', 'Интернешнл Петролеум Сервис (ИПС)_9мес_2026.json')
if os.path.exists(p):
    d = json.load(io.open(p, encoding='utf-8'))
    arts_r = {M.norm('Интернешнл Петролеум Сервис (ИПС)'): {2026: d}}
    row_r, _pr, _rk, _a, _b = M.build_row(arts_r, 'Интернешнл Петролеум Сервис (ИПС)')
    check('реальный ИПС: 4100/2026 = -7712', row_r.get(('4100', 2026)) == -7712,
          f'получено {row_r.get(("4100", 2026))!r}; колонки ОДДС {d.get("cash_flow", {}).get("columns")}')
    check('реальный ИПС: 4110/2026 = 161378', row_r.get(('4110', 2026)) == 161378,
          f'получено {row_r.get(("4110", 2026))!r}')
    check('реальный ИПС: 4100/2025 = -44779', row_r.get(('4100', 2025)) == -44779,
          f'получено {row_r.get(("4100", 2025))!r}')
    check('реальный ИПС: 4110/2025 = 573504', row_r.get(('4110', 2025)) == 573504,
          f'получено {row_r.get(("4110", 2025))!r}')
else:
    LOG.write('  (артефакт ИПС_9мес_2026 отсутствует — проверки на реальных данных пропущены)\n')

# ─── 7. модуль читает порядок строк, а не падает ───
check('порядок строк доступен (rows.txt на месте)', os.path.exists(M.ROWS), M.ROWS)
if os.path.exists(M.ROWS):
    n = sum(1 for line in io.open(M.ROWS, encoding='utf-8') if len(line.rstrip('\n').split('|')) == 3)
    check('в rows.txt 139 строк', n == 139, f'получено {n}')

LOG.write(f'\nИТОГ: успешно {ok}, провалов {fail}\n')
LOG.close()
print(f'успешно {ok}, провалов {fail} (лог: tests/_last_run_svod_9m_sources.txt)')
sys.exit(1 if fail else 0)
