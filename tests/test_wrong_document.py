# требующий ручной проверки. Проверяем каждое упоминание в СВОЁМ разделе, а не «где-то
# в аудите»: иначе проверка проходит по чужой строке.
def section(title):
    i = audit.find(title)
    if i < 0:
        return ''
    ends = [x for x in (audit.find('\n### ', i + len(title)),
                        audit.find('\n## ', i + len(title))) if x > 0]
    return audit[i:min(ends)] if ends else audit[i:]


def block(text, name):
    i = text.find(f'- **{name}**:')
    if i < 0:
        return ''
    j = text.find('\n- **', i + 1)
    return text[i:j] if j > 0 else text[i:]


